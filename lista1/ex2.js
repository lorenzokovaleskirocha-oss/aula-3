// 1. Declara a base e a altura do retângulo
const base = 10;
const altura = 5;

// 2. Calcula a área (base vezes altura)
const area = base * altura;

// 3. Calcula o perímetro (soma de todos os lados)
const perimetro = 2 * (base + altura);

// 4. Exibe os resultados em linhas separadas usando Template Strings
console.log(`A área do retângulo é: ${area} unidades quadradas.`);
console.log(`O perímetro do retângulo é: ${perimetro} unidades.`);