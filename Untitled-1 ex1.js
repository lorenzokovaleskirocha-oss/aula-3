// 1. Declara a temperatura em Celsius
const temperaturaCelsius = 25;

// 2. Converte para Fahrenheit usando a fórmula
const temperaturaFahrenheit = temperaturaCelsius * 1.8 + 32;

// 3. Exibe o resultado usando Template String
console.log(`A temperatura de ${temperaturaCelsius}°C equivale a ${temperaturaFahrenheit}°F.`);